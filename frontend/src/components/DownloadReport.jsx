function DownloadReport() {

  const download = () => {

    const data = `
AI Rockfall Prediction Report

Location: Shimla Ridge Highway
Risk Level: Medium

Generated by AI Rockfall Monitoring System
`;

    const blob = new Blob([data], { type: "text/plain" });

    const url = URL.createObjectURL(blob);

    const a = document.createElement("a");
    a.href = url;
    a.download = "rockfall_report.txt";
    a.click();

  };

  return (

    <button
      onClick={download}
      style={{
        marginTop: "20px",
        padding: "10px",
        background: "#2c3e50",
        color: "white",
        border: "none",
        cursor: "pointer"
      }}
    >
      Download Risk Report
    </button>

  );

}

export default DownloadReport;